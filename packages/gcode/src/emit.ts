import type { MultiPlateProject, BuildPlate, PurgeConfig, PlatePart } from "@nozzle-bench/engine";
import { sortPlatesByQueue, partsByExtruder } from "@nozzle-bench/engine";
import { resolvePartParameters } from "@nozzle-bench/engine";
import { generatePlateToolChangeGCode } from "./tool-change";

/**
 * Generate G-code header for the entire project.
 */
export function emitProjectHeader(project: MultiPlateProject): string {
  const lines = [
    `; NozzleBench G-code output`,
    `; Project: ${project.name}`,
    `; Plates: ${project.plates.length}`,
    `; Generated by @nozzle-bench/gcode`,
    "",
  ];
  return lines.join("\n");
}

/**
 * Generate G-code for a single plate, including tool-change sequences
 * and per-part processing.
 */
export function emitPlateGCode(
  project: MultiPlateProject,
  plate: BuildPlate,
  purge: PurgeConfig = { enabled: false, towerPosition: { x: 0, y: 0 }, towerSize: { width: 10, height: 10 }, purgeLength: 30 },
): string {
  const lines: string[] = [];

  lines.push(`; ===== Plate: ${plate.name} (${plate.id}) =====`);
  lines.push(`; Parts: ${plate.parts.length}`);

  // Emit tool-change preamble
  const toolChangeGCode = generatePlateToolChangeGCode(plate, purge);
  if (toolChangeGCode) {
    lines.push("; -- Tool changes --");
    lines.push(toolChangeGCode);
  }

  // Per-part processing
  const groups = partsByExtruder(plate);
  for (const [extruderIndex, parts] of groups) {
    lines.push(`; -- Extruder T${extruderIndex} --`);
    for (const part of parts) {
      const params = resolvePartParameters(project.globalProfile, plate, part);
      lines.push(`; Part: ${part.meshPart.name} (id=${part.partId})`);
      lines.push(`;   Layer height: ${params.layerHeight} mm`);
      lines.push(`;   Print speed: ${params.printSpeed} mm/s`);
      lines.push(`;   Temperature: ${params.nozzleTemperature}°C`);
      lines.push(`;   Flow rate: ${params.flowRate}`);
      lines.push(`;   Infill: ${params.infillDensity * 100}% ${params.infillPattern}`);
      lines.push(`;   Walls: ${params.wallCount}`);
      // In a full implementation, the engine would slice the mesh and emit
      // the actual move commands here. For now, we emit the resolved parameters
      // as a record of what would be used.
    }
  }

  return lines.join("\n");
}

/**
 * Generate complete G-code for an entire multi-plate project.
 * Plates are processed in queue order.
 */
export function emitProjectGCode(
  project: MultiPlateProject,
  purge: PurgeConfig = { enabled: false, towerPosition: { x: 0, y: 0 }, towerSize: { width: 10, height: 10 }, purgeLength: 30 },
): string {
  const sections: string[] = [];

  sections.push(emitProjectHeader(project));

  const orderedPlates = sortPlatesByQueue(project);
  for (const plate of orderedPlates) {
    sections.push(emitPlateGCode(project, plate, purge));
  }

  sections.push("; ===== End of G-code =====");
  return sections.join("\n");
}
